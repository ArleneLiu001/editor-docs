<h5 id="_1-文档分页显示问题" tabindex="-1"><a class="header-anchor" href="#_1-文档分页显示问题"><span>1.文档分页显示问题：</span></a></h5>
<p>现状： 需将整个文档进行动态分割成多个页面，每个页面的高度固定，遇到图片、表格元素，需解析判断元素高度计算进行特殊的分隔渲染。 手动js切割逻辑复杂，渲染效果待定。</p>
<p>风险： 影响长文档的用户体验和阅读流畅性，需明确处理方案和处理后效果。</p>
<h5 id="_2-文档目录生成与锚点失效" tabindex="-1"><a class="header-anchor" href="#_2-文档目录生成与锚点失效"><span>2.文档目录生成与锚点失效：</span></a></h5>
<p>需求： 后端需基于文档内容生成目录，点击目录项需跳转到对应内容区域（依赖标签ID）。</p>
<p>核心问题： WangEditor 会过滤非标准/自定义的标签属性（如 id）。</p>
<p>风险： 在导入或编辑时设置的用于锚点的 id 属性被编辑器清除，导致目录索引功能失效。</p>
<h5 id="_3-自定义控件的内容在编辑器中显示时-字数统计缺失" tabindex="-1"><a class="header-anchor" href="#_3-自定义控件的内容在编辑器中显示时-字数统计缺失"><span>3.自定义控件的内容在编辑器中显示时，字数统计缺失：</span></a></h5>
<p>问题： 用户通过自定义控件编辑的内容未被 WangEditor 的内部状态（如 editor.getHtml() 或 editor.getText()）正确捕获或统计。</p>
<p>风险： 导致内容字数统计错误。</p>
<h5 id="_4-内容插入方式的两难困境" tabindex="-1"><a class="header-anchor" href="#_4-内容插入方式的两难困境"><span>4.内容插入方式的两难困境：</span></a></h5>
<p>方案A (setHtml)：</p>
<p>优点： 编辑器原生方法，保证功能集成度。</p>
<p>缺点： 自动过滤自定义属性（如锚点 id），导致功能失效。</p>
<p>方案B (直接操作DOM)：</p>
<p>优点： 可自由添加任意属性（如 id），满足锚点需求。</p>
<p>缺点： 插入的内容区域在获得焦点时，编辑器的工具栏无法激活/使用，丧失编辑能力。</p>
<p>风险： 目前暂无完美的内容插入方案，既需保留自定义属性，又需保持编辑器对内容的完全控制。可研究方案B是否可以通过一定的方法主动激活工具栏功能。</p>
<h5 id="_5-文档格式渲染与导出问题" tabindex="-1"><a class="header-anchor" href="#_5-文档格式渲染与导出问题"><span>5.文档格式渲染与导出问题：</span></a></h5>
<p>导入渲染瑕疵： 部分导入文档的格式在编辑器中渲染效果不理想。导入时，和后端协商需要考虑锚点定位机制。</p>
<p>导出标题丢失： 文档导出时，存在标题信息丢失的问题。目前只支持word，是否需要支持其他格式。要考虑导出时，对锚点做相应的处理和标识方法和逻辑。</p>
<h5 id="_6-悬停自由添加组件功能" tabindex="-1"><a class="header-anchor" href="#_6-悬停自由添加组件功能"><span>6.悬停自由添加组件功能：</span></a></h5>
<p>涉及难点： 需要实现锚点定位机制，并解决锚点的动态生成与锚点排序逻辑。</p>
<p>风险： 功能实现复杂，锚点管理不当可能导致组件定位错误或性能问题。</p>
